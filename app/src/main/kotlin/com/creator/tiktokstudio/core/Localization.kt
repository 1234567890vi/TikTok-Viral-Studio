object Localization {
    val current: AppStrings
        @Composable
        get() {
            val lang = ThemeAndLocaleManager.currentLanguage.collectAsState().value
            return when (lang) {
                AppLanguage.ARABIC -> ArabicStrings
                AppLanguage.ENGLISH -> EnglishStrings
                AppLanguage.FRENCH -> FrenchStrings
            }
        }
}
